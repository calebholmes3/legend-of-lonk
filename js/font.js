const glyphCache = new Map(); // color -> { char: canvas }
function glyphsFor(col) {
  if (!glyphCache.has(col)) {
    const set = {};
    for (const [ch, rows] of Object.entries(GLYPHS)) set[ch] = makeSprite(rows, { '#': col });
    glyphCache.set(col, set);
  }
  return glyphCache.get(col);
}

// size is 8 (normal) or 16 (double-size headings); y is the top of the text
function text(s, x, y, col = '#fcfcfc', size = 8, align = 'left') {
  s = String(s);
  const k = size / 8, set = glyphsFor(col), w = s.length * 8 * k;
  let X = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const Y = Math.round(y);
  for (const ch of s) {
    const g = set[ch] || set[ch.toUpperCase()];
    if (g) ctx.drawImage(g, X, Y, g.width * k, g.height * k);
    X += 8 * k;
  }
}
